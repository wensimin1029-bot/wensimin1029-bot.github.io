// The nine final gaze stickers are registered in the same geometry. Keep one
// image on screen at a time: fading entire faces creates doubled eyelashes.
const gaze = q('[data-gaze]');
const hero = q('.hero');
const directions = ['center', 'left', 'right', 'up', 'down', 'up-left', 'up-right', 'down-left', 'down-right'];
const frames = new Map(directions.map(direction => {
  const image = new Image();
  image.src = `assets/${direction}.png${direction === 'down' ? '?v=20261023-gaze3' : direction === 'down-right' ? '?v=20261023-gaze2' : ''}`;
  return [direction, image];
}));
let currentDirection = 'center';
let horizontal = 0;
let vertical = 0;
let pendingPoint = null;
let gazeFrame = 0;
let lastSwitch = 0;
let delayedSwitch = 0;

function axis(value, current) {
  if (current === 0) return value > .35 ? 1 : value < -.35 ? -1 : 0;
  if (current > 0) return value < .13 ? 0 : 1;
  return value > -.13 ? 0 : -1;
}
function directionName(x, y) {
  const horizontalName = x < 0 ? 'left' : x > 0 ? 'right' : '';
  const verticalName = y < 0 ? 'up' : y > 0 ? 'down' : '';
  return verticalName && horizontalName ? `${verticalName}-${horizontalName}` : verticalName || horizontalName || 'center';
}
function showDirection(direction) {
  if (direction === currentDirection || !frames.get(direction)?.complete) return;
  gaze.src = frames.get(direction).src;
  currentDirection = direction;
  lastSwitch = performance.now();
}
function updateGaze() {
  gazeFrame = 0;
  if (!pendingPoint || reducedMotion.matches) return;
  const rect = hero.getBoundingClientRect();
  const dx = (pendingPoint.x - rect.left - rect.width * .5) / (rect.width * .43);
  const dy = (pendingPoint.y - rect.top - rect.height * .43) / (rect.height * .38);
  horizontal = axis(dx, horizontal);
  vertical = axis(dy, vertical);
  const next = directionName(horizontal, vertical);
  if (next === currentDirection) return;
  clearTimeout(delayedSwitch);
  const wait = Math.max(0, 95 - (performance.now() - lastSwitch));
  delayedSwitch = window.setTimeout(() => showDirection(next), wait);
}
function resetGaze() {
  pendingPoint = null;
  horizontal = 0;
  vertical = 0;
  clearTimeout(delayedSwitch);
  showDirection('center');
}
if (finePointer.matches) {
  hero.addEventListener('pointermove', event => {
    pendingPoint = { x: event.clientX, y: event.clientY };
    if (!gazeFrame) gazeFrame = requestAnimationFrame(updateGaze);
  }, { passive: true });
  hero.addEventListener('pointerleave', resetGaze);
  window.addEventListener('blur', resetGaze);
}
